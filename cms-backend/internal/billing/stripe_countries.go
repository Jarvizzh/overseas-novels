// Restricted customer locations under Stripe Managed Payments (MoR) per Stripe docs:
// China (CN), Cuba (CU), Iran (IR), North Korea (KP), Russia (RU),
// Saint Helena / Ascension Island / Tristan da Cunha (SH), Syria (SY).
// Non-ISO-3166-1 codes (Kosovo XK, AC, TA) are already outside allISO2Countries.
var stripeMoRRestrictedCountries = map[string]struct{}{
	"CN": {},
	"CU": {},
	"IR": {},
	"KP": {},
	"RU": {},
	"SH": {},
	"SY": {},
}

func defaultStripeCountriesForMode(salesMode string) []string {
	if salesMode == stripeManagedPayments {
		out := make([]string, 0, len(allISO2Countries)-len(stripeMoRRestrictedCountries))
		for _, code := range allISO2Countries {
			if _, restricted := stripeMoRRestrictedCountries[code]; restricted {
				continue
			}
			out = append(out, code)
		}
		return out
	}
	return slices.Clone(allISO2Countries)
}
